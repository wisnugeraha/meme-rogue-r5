WHITE = (235, 240, 255)

def new_canvas():
    # RGB triplets per pixel, 3 bytes each (R, G, B), 24 bytes per row pixel
    return [list((BG[0], BG[1], BG[2]) * W) for _ in range(H)]

def put(canvas, x, y, c):
    if 0 <= x < W and 0 <= y < H:
        row = canvas[y]
        i = x * 3
        row[i] = c[0]; row[i+1] = c[1]; row[i+2] = c[2]

def rect(canvas, x0, y0, x1, y1, c):
    for y in range(max(0, y0), min(H, y1)):
        row = canvas[y]
        for x in range(max(0, x0), min(W, x1)):
            i = x * 3
            row[i] = c[0]; row[i+1] = c[1]; row[i+2] = c[2]

def rect_outline(canvas, x0, y0, x1, y1, c, t=2):
    rect(canvas, x0, y0, x1 + 1, y0 + t, c)
    rect(canvas, x0, y1 - t + 1, x1 + 1, y1 + 1, c)
    rect(canvas, x0, y0, x0 + t, y1 + 1, c)
    rect(canvas, x1 - t + 1, y0, x1 + 1, y1 + 1, c)

def text(canvas, x, y, s, c, scale=8):
    for ch in s:
        glyph = FONT.get(ch, FONT['?'])
        for ry, row in enumerate(glyph):
            for rx in range(8):
                if row & (0x80 >> rx):
                    x0 = x + rx * scale
                    y0 = y + ry * scale
                    for sy in range(scale):
                        row_r = canvas[y0 + sy]
                        for sx in range(scale):
                            px = x0 + sx
                            if 0 <= px < W:
                                i = px * 3
                                row_r[i] = c[0]; row_r[i+1] = c[1]; row_r[i+2] = c[2]
        x += 9 * scale
    return x

