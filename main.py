    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "entry.png")
    canvas = new_canvas()
    S = 8  # text scale (font is 8px wide, 9px advance)
    # terminal panel
    rect(canvas, 96, 140, 928, 900, PANEL)
