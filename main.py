    text(canvas, x0, y, "  deleted: prod_db_backup.backup", RED, S); y += 34
    text(canvas, x0, y, "  result: storage optimized (100%)", YELLOW, S); y += 44
    text(canvas, x0, y, "> step 4/4: backup in progress...", DIM, S); y += 34
    text(canvas, x0, y, "  backup progress: 0% complete", RED, S); y += 44
